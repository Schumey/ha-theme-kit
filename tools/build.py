"""Builds the theme files from src/*.src.yaml and the CSS blocks in src/blocks/.

A line "@include name" (only spaces before it) is replaced by src/blocks/name.css,
indented like the line. Blocks may contain @include themselves.

Result: one finished file per theme (anchors and merge keys resolved) in
custom_components/<domain>/themes/<slug>.yaml. The integration copies the
selected files to /config/themes/<domain>/.

  python tools/build.py           # build
  python tools/build.py --check   # only check that the output is up to date
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
BLOCKS = SRC / "blocks"
INCLUDE = re.compile(r"^( *)@include ([\w-]+)\s*$")


def integration_dir():
    found = [p for p in (ROOT / "custom_components").iterdir() if (p / "manifest.json").exists()]
    if len(found) != 1:
        sys.exit("Error: expected exactly one integration in custom_components/")
    return found[0]


def expand(lines, stack=()):
    out = []
    for line in lines:
        m = INCLUDE.match(line)
        if not m:
            out.append(line)
            continue
        indent, name = m.groups()
        if name in stack:
            sys.exit(f"Error: @include {name} includes itself ({' > '.join(stack)})")
        path = BLOCKS / f"{name}.css"
        if not path.exists():
            sys.exit(f"Error: block {path.name} is missing")
        block = path.read_text(encoding="utf-8").rstrip("\n").split("\n")
        for b in expand(block, stack + (name,)):
            out.append(indent + b if b.strip() else "")
    return out


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, value):
    # multi-line strings (uix-*-yaml) as a block instead of one long line
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, _str)


def build_all(integration):
    """Returns {file name: text}, one file per theme."""
    version = json.loads((integration / "manifest.json").read_text(encoding="utf-8"))["version"]
    files = {}
    sources = sorted(SRC.glob("*.src.yaml"))
    if not sources:
        sys.exit("Error: no src/*.src.yaml found")
    for source in sources:
        text = "\n".join(expand(source.read_text(encoding="utf-8").split("\n")))
        for name, values in yaml.safe_load(text).items():
            head = (
                f"# theme-name: {name}\n"
                f"# Version: {version}\n"
                "# Generated by tools/build.py, do not edit by hand.\n"
            )
            body = yaml.dump({name: values}, Dumper=Dumper, allow_unicode=True,
                             sort_keys=False, width=1_000_000)
            files[slug(name) + ".yaml"] = head + "\n" + body
    return files


def main():
    integration = integration_dir()
    out = integration / "themes"
    files = build_all(integration)
    old = {p.name: p.read_text(encoding="utf-8") for p in out.glob("*.yaml")} if out.exists() else {}
    if "--check" in sys.argv:
        if files != old:
            sys.exit("Theme files are out of date, please run tools/build.py")
        print(f"{len(files)} theme files are up to date")
        return
    out.mkdir(parents=True, exist_ok=True)
    for name in old.keys() - files.keys():
        (out / name).unlink()
    changed = 0
    for name, text in files.items():
        if old.get(name) != text:
            (out / name).write_text(text, encoding="utf-8", newline="\n")
            changed += 1
    print(f"{len(files)} theme files, {changed} written")


if __name__ == "__main__":
    main()
